'use client';

import type { MeetingDetailDto } from '@allfina/shared';
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { AlertTriangle, Check, Copy, Loader2, RotateCw, Trash2 } from 'lucide-react';
import Link from 'next/link';
import { useParams, useRouter } from 'next/navigation';
import { useState } from 'react';
import { StatusBadge } from '@/components/status-badge';
import { Button } from '@/components/ui/button';
import { Card, CardBody, CardHeader } from '@/components/ui/card';
import { api } from '@/lib/api';
import { formatDate } from '@/lib/utils';

export default function MeetingDetailPage() {
  const { id } = useParams<{ id: string }>();
  const router = useRouter();
  const queryClient = useQueryClient();
  const queryKey = ['meetings', id];

  const {
    data: meeting,
    isLoading,
    error,
  } = useQuery({
    queryKey,
    queryFn: () => api<MeetingDetailDto>(`/meetings/${id}`),
    refetchInterval: (q) => (q.state.data?.status === 'processing' ? 4000 : false),
  });

  const process = useMutation({
    mutationFn: () => api(`/meetings/${id}/process`, { method: 'POST' }),
    onSuccess: () => queryClient.invalidateQueries({ queryKey }),
  });

  const remove = useMutation({
    mutationFn: () => api(`/meetings/${id}`, { method: 'DELETE' }),
    onSuccess: async () => {
      await queryClient.invalidateQueries({ queryKey: ['meetings'] });
      router.replace('/meetings');
    },
  });

  const toggleItem = useMutation({
    mutationFn: ({ itemId, completed }: { itemId: string; completed: boolean }) =>
      api(`/meetings/${id}/action-items/${itemId}`, {
        method: 'PATCH',
        body: JSON.stringify({ completed }),
      }),
    onMutate: ({ itemId, completed }) => {
      queryClient.setQueryData<MeetingDetailDto>(
        queryKey,
        (old) =>
          old && {
            ...old,
            actionItems: old.actionItems.map((i) => (i.id === itemId ? { ...i, completed } : i)),
          },
      );
    },
    onError: () => queryClient.invalidateQueries({ queryKey }),
  });

  if (isLoading) return <p className="text-sm text-slate-500">Loading…</p>;
  if (error || !meeting) return <p className="text-sm text-red-600">{error?.message}</p>;

  const canProcess = meeting.status === 'ready' || meeting.status === 'failed';

  return (
    <div className="space-y-6">
      <div>
        <Link href="/meetings" className="text-sm text-slate-500 hover:text-slate-700">
          ← Meetings
        </Link>
        <div className="mt-2 flex flex-wrap items-start justify-between gap-4">
          <div>
            <div className="flex items-center gap-3">
              <h1 className="text-2xl font-semibold tracking-tight">{meeting.title}</h1>
              <StatusBadge status={meeting.status} />
            </div>
            <p className="mt-1 text-sm text-slate-500">
              {meeting.client ? `${meeting.client.firstName} ${meeting.client.lastName} · ` : ''}
              {formatDate(meeting.scheduledAt ?? meeting.createdAt)}
            </p>
          </div>
          <div className="flex gap-2">
            {canProcess && (
              <Button
                variant="secondary"
                onClick={() => process.mutate()}
                disabled={process.isPending}
              >
                <RotateCw className="size-4" aria-hidden />
                {meeting.status === 'failed' ? 'Retry' : 'Analyze'}
              </Button>
            )}
            <Button
              variant="ghost"
              onClick={() => {
                if (window.confirm('Delete this meeting and all its notes?')) remove.mutate();
              }}
              disabled={remove.isPending}
              aria-label="Delete meeting"
            >
              <Trash2 className="size-4" aria-hidden />
            </Button>
          </div>
        </div>
      </div>

      {meeting.status === 'processing' && (
        <div className="flex items-center gap-3 rounded-lg border border-amber-200 bg-amber-50 px-4 py-3 text-sm text-amber-900">
          <Loader2 className="size-4 animate-spin" aria-hidden />
          AllFina is transcribing and analyzing this meeting. This page updates automatically.
        </div>
      )}
      {meeting.status === 'failed' && meeting.errorMessage && (
        <div className="rounded-lg border border-red-200 bg-red-50 px-4 py-3 text-sm text-red-800">
          Processing failed: {meeting.errorMessage}
        </div>
      )}

      {meeting.summary && (
        <>
          <Card>
            <CardHeader title="Summary" description={`Generated by ${meeting.summary.model}`} />
            <CardBody className="space-y-4">
              <p className="text-sm leading-6 whitespace-pre-line">{meeting.summary.summary}</p>
              {meeting.summary.keyPoints.length > 0 && (
                <ul className="list-disc space-y-1 pl-5 text-sm text-slate-700">
                  {meeting.summary.keyPoints.map((p, i) => (
                    <li key={i}>{p}</li>
                  ))}
                </ul>
              )}
            </CardBody>
          </Card>

          {meeting.summary.complianceFlags.length > 0 && (
            <Card className="border-amber-300">
              <CardHeader
                title="Compliance review"
                description="Items flagged for your compliance team to review."
              />
              <CardBody>
                <ul className="space-y-2 text-sm">
                  {meeting.summary.complianceFlags.map((f, i) => (
                    <li key={i} className="flex gap-2">
                      <AlertTriangle
                        className="mt-0.5 size-4 shrink-0 text-amber-600"
                        aria-hidden
                      />
                      {f}
                    </li>
                  ))}
                </ul>
              </CardBody>
            </Card>
          )}

          <Card>
            <CardHeader title="Action items" />
            <CardBody>
              {meeting.actionItems.length === 0 ? (
                <p className="text-sm text-slate-500">No action items were identified.</p>
              ) : (
                <ul className="divide-y divide-slate-100">
                  {meeting.actionItems.map((item) => (
                    <li key={item.id} className="flex items-start gap-3 py-2.5">
                      <input
                        type="checkbox"
                        checked={item.completed}
                        onChange={(e) =>
                          toggleItem.mutate({ itemId: item.id, completed: e.target.checked })
                        }
                        className="mt-0.5 size-4 rounded border-slate-300 accent-brand-600"
                        aria-label={item.description}
                      />
                      <div className="flex-1 text-sm">
                        <p className={item.completed ? 'text-slate-400 line-through' : ''}>
                          {item.description}
                        </p>
                        <p className="mt-0.5 text-xs text-slate-500 capitalize">
                          {item.owner}
                          {item.dueDate ? ` · due ${item.dueDate}` : ''}
                        </p>
                      </div>
                    </li>
                  ))}
                </ul>
              )}
            </CardBody>
          </Card>

          <FollowUpEmail
            subject={meeting.summary.followUpEmailSubject}
            body={meeting.summary.followUpEmailBody}
          />
        </>
      )}

      {meeting.transcript && (
        <Card>
          <details>
            <summary className="cursor-pointer px-5 py-4 text-base font-semibold">
              Transcript
            </summary>
            <CardBody className="border-t border-slate-200">
              <pre className="max-h-[32rem] overflow-y-auto font-sans text-sm leading-6 whitespace-pre-wrap text-slate-700">
                {meeting.transcript.text}
              </pre>
            </CardBody>
          </details>
        </Card>
      )}
    </div>
  );
}

function FollowUpEmail({ subject, body }: { subject: string; body: string }) {
  const [copied, setCopied] = useState(false);

  async function copy() {
    await navigator.clipboard.writeText(`Subject: ${subject}\n\n${body}`);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  }

  return (
    <Card>
      <CardHeader
        title="Follow-up email draft"
        description="Review before sending to your client."
        action={
          <Button variant="secondary" size="sm" onClick={copy}>
            {copied ? <Check className="size-4" /> : <Copy className="size-4" />}
            {copied ? 'Copied' : 'Copy'}
          </Button>
        }
      />
      <CardBody className="space-y-3 text-sm">
        <p>
          <span className="text-slate-500">Subject:</span>{' '}
          <span className="font-medium">{subject}</span>
        </p>
        <p className="leading-6 whitespace-pre-line text-slate-700">{body}</p>
      </CardBody>
    </Card>
  );
}
